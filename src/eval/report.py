import argparse
import json
import os


def load(path):
    if not os.path.exists(path):
        raise SystemExit(f"missing {path} — run the baseline and finetuned evals first")
    with open(path) as f:
        return json.load(f)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--domain", required=True)
    args = parser.parse_args()

    results_dir = os.path.join("domains", args.domain, "results")
    baseline = load(os.path.join(results_dir, "baseline.json"))
    finetuned = load(os.path.join(results_dir, "finetuned.json"))

    lines = [
        f"# {args.domain} — results",
        "",
        "Generated by `python -m src.eval.report --domain " + args.domain + "`.",
        "",
        "| Eval | Metric | Baseline | Finetuned | Change |",
        "|---|---|---|---|---|",
    ]

    for key in baseline:
        if key not in finetuned:
            continue
        b, f_ = baseline[key], finetuned[key]
        delta = f_["value"] - b["value"]
        improved = delta > 0 if b["higher_is_better"] else delta < 0
        marker = "" if abs(delta) < 1e-9 else (" ✅" if improved else " ⚠️")
        lines.append(
            f"| {key} | {b['metric']} | {b['value']:.4f} | {f_['value']:.4f} | {delta:+.4f}{marker} |"
        )

    only_baseline = sorted(set(baseline) - set(finetuned))
    only_finetuned = sorted(set(finetuned) - set(baseline))
    if only_baseline or only_finetuned:
        lines += [
            "",
            "Unpaired evals (ran on only one side, so no comparison is possible): "
            + ", ".join(only_baseline + only_finetuned),
        ]

    lines += [
        "",
        "⚠️ marks a metric that moved the wrong way. A held-out perplexity drop shows "
        "the model fit the domain distribution; read it alongside the benchmark rows, "
        "which are what indicate capability.",
        "",
    ]

    report = "\n".join(lines)
    with open(os.path.join(results_dir, "report.md"), "w") as f:
        f.write(report)
    print(report)


if __name__ == "__main__":
    main()
